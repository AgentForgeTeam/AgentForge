"""Место подзадачи в цепочке: от кого она получает данные и кому их передаёт.

Агенту и супервайзеру показывается общая задача проекта целиком, и без
пометки они считали, что каждая подзадача должна ответить на неё. Замер на
открытых бенчмарках это выявил: супервайзер возвращал верные промежуточные
результаты с замечанием «не отвечает на основной вопрос проекта», после
доработки результат оставался непринятым, и зависимые подзадачи не
запускались. Пометка говорит, чего ждать от этапа: промежуточный отвечает
только на свою часть, итоговый собирает ответ на всю задачу.

Для подзадачи вне цепочки (без зависимостей в обе стороны) пометки нет,
и тексты для модели остаются прежними.
"""

from __future__ import annotations

from storage.models import Subtask


def _ids(raw: str | None) -> set[int]:
    return {int(t) for t in (raw or "").split(",") if t.strip().isdigit()}


def _titles(subtasks: list[Subtask]) -> str:
    return ", ".join(f"«{s.title}»" for s in subtasks)


def chain_note(subtasks: list[Subtask], subtask: Subtask, *, for_supervisor: bool) -> str:
    """Пометка о месте подзадачи в цепочке или пустая строка."""
    before = [s for s in subtasks if s.id in _ids(subtask.depends_on)]
    after = [s for s in subtasks if subtask.id in _ids(s.depends_on)]
    if after:
        if for_supervisor:
            return (f"МЕСТО В ЦЕПОЧКЕ: промежуточный этап, его результат получит "
                    f"{_titles(after)}. Оценивай только то, что требует этот этап. Ответ на "
                    "всю задачу и её итоговый формат (например строка ANSWER:) от него не "
                    "требуются, их даст последний этап.")
        return (f"МЕСТО В ЦЕПОЧКЕ: это промежуточный этап, его результат получит "
                f"{_titles(after)}. Выполни только свою часть. Ответ на всю задачу и её "
                "итоговый формат (например строка ANSWER:) здесь не нужны, их даст последний этап.")
    if before:
        if for_supervisor:
            return (f"МЕСТО В ЦЕПОЧКЕ: итоговый этап, он собирает ответ на всю задачу из "
                    f"результатов {_titles(before)}. Здесь требуй ответ на всю задачу в "
                    "формате, который она просит.")
        return (f"МЕСТО В ЦЕПОЧКЕ: это итоговый этап. Собери из результатов {_titles(before)} "
                "ответ на всю задачу в формате, который она требует.")
    return ""
