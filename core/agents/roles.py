def by_key(key: str) -> RoleTemplate:
    for t in TEMPLATES:
        if t.key == key:
            return t
    return TEMPLATES[-1]


def title(template: RoleTemplate, lang: str) -> str:
    return template.title_en if lang == "en" else template.title_ru
