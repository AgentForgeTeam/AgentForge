def package_inits() -> list[str]:
    """Файлы ``__init__.py`` перечисляются списком: они содержат одну строку."""
    return sorted(str(p.relative_to(ROOT)) for p in ROOT.rglob("__init__.py"))


def render_file(relative: str) -> str:
    path = ROOT / relative
    if not path.exists():
        return f"### `{relative}`\n\n*Файл не найден при сборке документа.*\n"
    body = path.read_text("utf-8").rstrip("\n")
    lines = body.count("\n") + 1
    return (
        f"### `{relative}`\n\n"
        f"*{lines} строк*\n\n"
        f"{FENCE}{language_of(path)}\n{body}\n{FENCE}\n"
    )


